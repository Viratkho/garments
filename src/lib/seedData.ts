function daysAgo(base: Date, days: number): string {
  const d = new Date(base);
  d.setDate(d.getDate() - days);
  return toISODate(d);
}

function daysAhead(base: Date, days: number): string {
  const d = new Date(base);
  d.setDate(d.getDate() + days);
  return toISODate(d);
}

function monthDay(base: Date, monthsBack: number, day: number): string {
  const d = new Date(base.getFullYear(), base.getMonth() - monthsBack, Math.min(day, 28));
  return toISODate(d);
}

